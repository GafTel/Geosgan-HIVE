TOOL_CALL_INSTRUCTIONS = """\
When you need to use a tool, reply ONLY with a JSON like:
{"tool": "<tool_name>", "args": {"<parameter>": "<value>"}}
Do not add any text outside the JSON. When you have the final answer, reply in plain text."""

DELEGATION_INSTRUCTIONS = """\
You may delegate subtasks to other agents through the collaboration engine.
Reply ONLY with a JSON:
- Single delegation:
  {"delegate": {"target": "<agent>", "task": "<subtask>", "reason": "<why>",
                 "context_hints": ["..."]}}
- Multiple independent delegations (the runtime executes them with bounded concurrency):
  {"delegations": [{"target": "...", "task": "...", "reason": "..."}, ...]}
You only choose target, task, reason and optional context hints. The runtime assigns
request/task/run identifiers and enforces permissions, depth and budget limits.
Delegation results come back to you as messages; then continue or reply with your
final answer in plain text."""


@dataclass
class ToolCall:
    tool: str
    args: dict[str, Any]
    result: str


@dataclass
class AgentResult:
    agent: str
    answer: str
    tool_calls: list[ToolCall] = field(default_factory=list)
    steps: int = 0
    handoffs: list[Any] = field(default_factory=list)  # list[HandoffResult]


def parse_json_object(text: str) -> dict[str, Any] | None:
    text = text.strip()
    if text.startswith("```"):
        lines = text.splitlines()
        text = "\n".join(lines[1:]).removesuffix("```").strip()
    if not (text.startswith("{") and text.endswith("}")):
        start, end = text.find("{"), text.rfind("}")
        if start == -1 or end <= start:
            return None
        text = text[start : end + 1]
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        return None
    return data if isinstance(data, dict) else None


def parse_tool_call(text: str) -> dict[str, Any] | None:
    data = parse_json_object(text)
    if data and isinstance(data.get("tool"), str) and isinstance(data.get("args"), dict):
        return data
    return None


def parse_delegation_call(text: str) -> tuple[str, list[dict[str, Any]]] | None:
    """Parse a model delegation action.

    Returns ("single", [payload]) or ("many", [payloads]), or None. Only
    model-chosen fields survive downstream; identifiers and permissions are
    generated by the CollaborationEngine, never taken from this JSON.
    """
    data = parse_json_object(text)
    if not isinstance(data, dict):
        return None
    if isinstance(data.get("delegate"), dict):
        return ("single", [data["delegate"]])
    delegations = data.get("delegations")
    if (
        isinstance(delegations, list)
        and delegations
        and all(isinstance(d, dict) for d in delegations)
    ):
        return ("many", delegations)
    return None


def check_run_limits(
    tracker: UsageTracker | None,
    run_id: str | None,
    calls: int,
    limits: Limits,
) -> str | None:
    """Return a stop message when a hard per-agent limit is reached.

    The cost budget is a soft limit: it is only enforced while the run's cost is
    reliably known (`cost_for_run` returns None when any call of the run has an
    unknown cost, e.g. a local model), so we never claim budget enforcement on
    unreliable cost data.
    """
    if calls >= limits.max_calls_per_run:
        return f"Execution limit reached: max {limits.max_calls_per_run} model calls per run."
    if tracker is not None and run_id is not None and limits.max_cost_usd_per_run is not None:
        cost = tracker.cost_for_run(run_id)
        if cost is not None and cost >= limits.max_cost_usd_per_run:
            return (
                f"Cost budget reached: known spend ${cost:.4f} >= "
                f"limit ${limits.max_cost_usd_per_run:.4f}."
            )
    return None


class Agent:
    """Individual agent with a bounded tool/delegation loop until it answers.

    Least privilege: only the tools explicitly allowed in `permissions` are
    visible to the model, and delegation only works when `allow_delegation` is
    set AND a CollaborationEngine is attached. Delegation actions never carry
    trusted metadata — the engine generates all identifiers.
    """

    def __init__(
        self,
        name: str,
        description: str,
        system_prompt: str,
        llm: LLMClient,
        tools: ToolRegistry | None = None,
        *,
        permissions: Permissions | None = None,
        limits: Limits | None = None,
        usage_tracker: UsageTracker | None = None,
        temperature: float = 0.2,
        collaboration: CollaborationEngine | None = None,
    ) -> None:
        self.name = name
        self.description = description
        self.system_prompt = system_prompt
        self.llm = llm
        self.permissions = permissions or Permissions()
        self.limits = limits or Limits()
        self.usage_tracker = usage_tracker
        self.temperature = temperature
        self.collaboration = collaboration
        self.tools = self._effective_registry(tools or ToolRegistry())

    def _effective_registry(self, registry: ToolRegistry) -> ToolRegistry:
        if not self.permissions.allow_tools:
            return ToolRegistry()
        allowed = []
        for name in self.permissions.allowed_tools:
            tool = registry.get(name)
            if tool is None:
                raise ConfigError(
                    f"Agent '{self.name}' allows unknown tool '{name}'. "
                    f"Registered tools: {registry.names()}"
                )
            allowed.append(tool)
        return ToolRegistry(allowed)

    def _system_message(self) -> Message:
        prompt = self.system_prompt
        schemas = self.tools.schemas()
        if schemas:
            prompt += "\n\nAvailable tools:\n"
            prompt += json.dumps(schemas, ensure_ascii=False, indent=2)
            prompt += "\n\n" + TOOL_CALL_INSTRUCTIONS
        if self.permissions.allow_delegation:
            # delegation instructions appear whenever delegation is permitted,
            # even when the agent has no tools enabled
            prompt += "\n\n" + DELEGATION_INSTRUCTIONS
        return Message(role="system", content=prompt, agent=self.name)

    def _check_limits(
        self, run_id: str | None, calls: int, run_context: RunContext | None,
        task_id: str | None = None,
    ) -> str | None:
        stop = check_run_limits(self.usage_tracker, run_id, calls, self.limits)
        if stop is not None:
            return stop
        if run_context is not None:
            cap = run_context.policy.max_provider_requests_per_run
            if cap is not None and run_context.physical_requests >= cap:
                return (
                    f"Provider-request limit ({cap}) reached for this run "
                    f"(physical requests incl. retries)."
                )
            # atomic check+reserve: run-wide budget AND per-agent run-wide limit
            # (repeated delegation cannot reset the per-agent limit)
            ok, reason = run_context.reserve_model_call_for(
                self.name, task_id, self.limits.max_calls_per_run
            )
            if not ok:
                return reason
        return None

    def _delegation_allowed(self, run_context: RunContext | None) -> bool:
        return (
            self.collaboration is not None
            and run_context is not None
            and self.permissions.allow_delegation
        )

    @staticmethod
    def _format_handoff(res: HandoffResult) -> str:
        payload = res.result or res.error or ""
        return (
            f"Delegation result from '{res.target_agent}' (task {res.task_id}, "
            f"status {res.status.value}): {payload}"
        )

    def _process_tool_action(
        self,
        raw: str,
        call: dict[str, Any],
        messages: list[Message],
        tool_calls: list[ToolCall],
    ) -> None:
        if len(tool_calls) >= self.limits.max_tool_steps:
            messages.append(Message(role="assistant", content=raw, agent=self.name))
            messages.append(
                Message(
                    role="user",
                    agent="system",
                    content=(
                        "You have reached the maximum number of tool calls. "
                        "Reply now with the final answer in plain text."
                    ),
                )
            )
            return
        result = self.tools.run(call["tool"], call["args"])
        tool_calls.append(ToolCall(tool=call["tool"], args=call["args"], result=result))
        messages.append(Message(role="assistant", content=raw, agent=self.name))
        messages.append(
            Message(role="user", agent="tool", content=f"Result of '{call['tool']}': {result}")
        )

    def _parse_proposals(self, payloads: list[dict[str, Any]]) -> list[DelegationProposal]:
        from .collaboration import DelegationProposal

        return [DelegationProposal.model_validate(p) for p in payloads]

    def _run_delegations_sync(
        self,
        proposals: list[DelegationProposal],
        *,
        kind: str,
        run_id: str | None,
        task_id: str | None,
        run_context: RunContext,
    ) -> list[HandoffResult]:
        engine = self.collaboration
        assert engine is not None
        if kind == "many":
            return engine.delegate_many(
                proposals, run_id=run_id, parent_task_id=task_id, source_agent=self.name
            )
        return [
            engine.delegate(
                proposals[0], run_id=run_id, parent_task_id=task_id, source_agent=self.name
            )
        ]

    async def _run_delegations_async(
        self,
        proposals: list[DelegationProposal],
        *,
        kind: str,
        run_id: str | None,
        task_id: str | None,
        run_context: RunContext,
    ) -> list[HandoffResult]:
        engine = self.collaboration
        assert engine is not None
        if kind == "many":
            return await engine.adelegate_many(
                proposals, run_id=run_id, parent_task_id=task_id, source_agent=self.name
            )
        return [
            await engine.adelegate(
                proposals[0], run_id=run_id, parent_task_id=task_id, source_agent=self.name
            )
        ]

    def _prepare_delegation(
        self,
        raw: str,
        payloads: list[dict[str, Any]],
        messages: list[Message],
        *,
        run_id: str | None,
        task_id: str | None,
        run_context: RunContext | None,
    ) -> list[DelegationProposal] | None:
        """Validate + parse a model delegation action; appends feedback messages.

        Returns the parsed proposals, or None when the action is not permitted or
        malformed (the loop then continues with the feedback in `messages`).
        """
        messages.append(Message(role="assistant", content=raw, agent=self.name))
        if not self._delegation_allowed(run_context):
            messages.append(
                Message(
                    role="user",
                    agent="system",
                    content=(
                        "Delegation is not permitted for this agent. "
                        "Reply now with the final answer in plain text."
                    ),
                )
            )
            return None
        try:
            return self._parse_proposals(payloads)
        except Exception as exc:  # pydantic ValidationError -> malformed, rejected
            messages.append(
                Message(
                    role="user",
                    agent="system",
                    content=f"Malformed delegation request rejected: {exc}",
                )
            )
            return None

    def _record_handoffs(
        self, results: list[HandoffResult], messages: list[Message], handoffs: list[Any]
    ) -> None:
        handoffs.extend(results)
        for res in results:
            messages.append(
                Message(role="user", agent=res.target_agent, content=self._format_handoff(res))
            )

    def run(
        self,
        task: str,
        context: Sequence[Message] = (),
        *,
        run_id: str | None = None,
        task_id: str | None = None,
        run_context: RunContext | None = None,
    ) -> AgentResult:
        messages = [self._system_message(), *context, Message(role="user", content=task)]
        tool_calls: list[ToolCall] = []
        handoffs: list[Any] = []
        calls = 0
        max_iterations = self.limits.max_tool_steps + 2
        raw = ""
        for step in range(1, max_iterations + 1):
            stop = self._check_limits(run_id, calls, run_context, task_id)
            if stop is not None:
                return AgentResult(self.name, stop, tool_calls, step - 1, handoffs)
            raw = self.llm.complete(messages, temperature=self.temperature, run_id=run_id)
            calls += 1
            call = parse_tool_call(raw)
            if call is not None:
                self._process_tool_action(raw, call, messages, tool_calls)
                continue
            delegation = parse_delegation_call(raw)
            if delegation is not None:
                kind, payloads = delegation
                proposals = self._prepare_delegation(
                    raw, payloads, messages,
                    run_id=run_id, task_id=task_id, run_context=run_context,
                )
                if proposals is not None:
                    results = self._run_delegations_sync(
                        proposals, kind=kind, run_id=run_id, task_id=task_id,
                        run_context=run_context,
                    )
                    self._record_handoffs(results, messages, handoffs)
                continue
            return AgentResult(self.name, raw, tool_calls, step, handoffs)
        return AgentResult(self.name, raw, tool_calls, max_iterations, handoffs)

    async def arun(
        self,
        task: str,
        context: Sequence[Message] = (),
        *,
        run_id: str | None = None,
        task_id: str | None = None,
        run_context: RunContext | None = None,
    ) -> AgentResult:
        """Native async twin of `run`. Uses the LLM client's `acomplete` when
        available; legacy sync-only clients fall back to a thread (never the
        other way around)."""
        messages = [self._system_message(), *context, Message(role="user", content=task)]
        tool_calls: list[ToolCall] = []
        handoffs: list[Any] = []
        calls = 0
        max_iterations = self.limits.max_tool_steps + 2
        raw = ""
        acomplete = getattr(self.llm, "acomplete", None)
        for step in range(1, max_iterations + 1):
            stop = self._check_limits(run_id, calls, run_context, task_id)
            if stop is not None:
                return AgentResult(self.name, stop, tool_calls, step - 1, handoffs)
            if acomplete is not None:
                async def call():
                    return await acomplete(messages, temperature=self.temperature, run_id=run_id)
            else:  # legacy sync-only adapter: thread fallback only
                async def call():
                    return await asyncio.to_thread(
                        self.llm.complete, messages, temperature=self.temperature, run_id=run_id
                    )
            if run_context is not None:
                # bound ACTIVE model requests; never held while awaiting subtasks
                async with run_context.semaphore():
                    raw = await call()
            else:
                raw = await call()
            calls += 1
            call = parse_tool_call(raw)
            if call is not None:
                self._process_tool_action(raw, call, messages, tool_calls)
                continue
            delegation = parse_delegation_call(raw)
            if delegation is not None:
                kind, payloads = delegation
                proposals = self._prepare_delegation(
                    raw, payloads, messages,
                    run_id=run_id, task_id=task_id, run_context=run_context,
                )
                if proposals is not None:
                    results = await self._run_delegations_async(
                        proposals, kind=kind, run_id=run_id, task_id=task_id,
                        run_context=run_context,
                    )
                    self._record_handoffs(results, messages, handoffs)
                continue
            return AgentResult(self.name, raw, tool_calls, step, handoffs)
        return AgentResult(self.name, raw, tool_calls, max_iterations, handoffs)


async def arun_agent(
    agent: Agent,
    task: str,
    context: Sequence[Message] = (),
    *,
    run_id: str | None = None,
    task_id: str | None = None,
    run_context: RunContext | None = None,
) -> AgentResult:
    """Run an agent natively async when its LLM client supports `acomplete`.

    Legacy synchronous-only LLM adapters fall back to `asyncio.to_thread` —
    the thread fallback never replaces the native async execution path.
    """
    if hasattr(agent.llm, "acomplete"):
        return await agent.arun(
            task, context, run_id=run_id, task_id=task_id, run_context=run_context
        )
    return await asyncio.to_thread(
        agent.run, task, context, run_id=run_id, task_id=task_id, run_context=run_context
    )
