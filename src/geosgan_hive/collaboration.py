from __future__ import annotations

import asyncio
import threading
from enum import StrEnum
from typing import TYPE_CHECKING, Any
from uuid import uuid4

from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from .agents import arun_agent
from .errors import GatewayError
from .messages import Message
from .run_context import CollaborationPolicy, EventType, RunContext, TaskStatus, utcnow
from .usage import UsageTracker

if TYPE_CHECKING:
    from .agents import Agent


class DelegationStatus(StrEnum):
    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"


class DelegationProposal(BaseModel):
    """The ONLY fields a model may choose when requesting a delegation.

    Identifiers and permissions (request_id, run_id, task_id, parent_task_id,
    source_agent, delegation_depth) are generated by the runtime and never
    trusted from model-generated JSON (extra keys are ignored).
    """

    model_config = ConfigDict(extra="ignore")

    target: str = Field(min_length=1)
    task: str = Field(min_length=1)
    reason: str = ""
    context_hints: list[str] = Field(default_factory=list, max_length=10)


class HandoffRequest(BaseModel):
    """Fully runtime-generated handoff request (strict: extra keys forbidden)."""

    model_config = ConfigDict(extra="forbid")

    request_id: str
    run_id: str
    task_id: str
    parent_task_id: str | None
    source_agent: str
    target_agent: str
    task_description: str = Field(min_length=1)
    reason: str = ""
    relevant_context: list[Message] = Field(default_factory=list)
    delegation_depth: int = Field(ge=1)

    @model_validator(mode="after")
    def _no_self_delegation(self) -> HandoffRequest:
        if self.source_agent == self.target_agent:
            raise ValueError("self-delegation is not allowed")
        return self


class HandoffResult(BaseModel):
    """Structured result of a delegated subtask, returned to the source agent."""

    task_id: str
    request_id: str
    run_id: str
    source_agent: str
    target_agent: str
    status: DelegationStatus
    result: str = ""
    error: str | None = None
    delegation_depth: int = 0
    model_calls: int = 0  # exact count of model requests made by the subtask (incl. nested)
    started_at: str = ""
    finished_at: str | None = None


class CollaborationEngine:
    """Central authority for agent-to-agent delegation.

    Agents never call each other directly: every handoff goes through
    `delegate`/`adelegate` (or `delegate_many`/`adelegate_many`), which build the
    trusted HandoffRequest, validate it against policy + permissions, record
    events, execute the target agent and return a structured HandoffResult.
    RunContexts are isolated per run_id and evicted when closed or over capacity.
    """

    def __init__(
        self,
        policy: CollaborationPolicy | None = None,
        tracker: UsageTracker | None = None,
        agents: dict[str, Agent] | None = None,
        *,
        max_cached_runs: int = 32,
    ) -> None:
        self.policy = policy or CollaborationPolicy()
        self.tracker = tracker if tracker is not None else UsageTracker()
        self.agents: dict[str, Agent] = dict(agents or {})
        self.max_cached_runs = max_cached_runs
        self._contexts: dict[str, RunContext] = {}
        self._lock = threading.Lock()

    def register(self, agents: dict[str, Agent]) -> None:
        self.agents.update(agents)

    # ---- run context lifecycle ----
    def context_for(self, run_id: str) -> RunContext:
        with self._lock:
            ctx = self._contexts.get(run_id)
            if ctx is None:
                if len(self._contexts) >= self.max_cached_runs:
                    oldest = next(iter(self._contexts))
                    self._contexts.pop(oldest, None)
                ctx = RunContext(run_id, self.policy, self.tracker)
                self._contexts[run_id] = ctx
            return ctx

    def close_run(self, run_id: str) -> None:
        with self._lock:
            ctx = self._contexts.pop(run_id, None)
        if ctx is not None:
            ctx.close()

    def active_runs(self) -> int:
        with self._lock:
            return len(self._contexts)

    # ---- trusted request construction + validation ----
    def _build_request(
        self,
        proposal: DelegationProposal,
        *,
        run_id: str,
        parent_task_id: str | None,
        source_agent: str,
        ctx: RunContext,
    ) -> HandoffRequest:
        parent = ctx.task(parent_task_id) if parent_task_id else None
        depth = parent.depth + 1 if parent else 1
        context = ctx.scoped_context(parent_task_id) if parent_task_id else []
        hints = [
            Message(role="user", agent=source_agent, content=f"Context hint: {h}")
            for h in proposal.context_hints
        ]
        return HandoffRequest(
            request_id=uuid4().hex,
            run_id=run_id,
            task_id=uuid4().hex,
            parent_task_id=parent_task_id,
            source_agent=source_agent,
            target_agent=proposal.target,
            task_description=proposal.task,
            reason=proposal.reason,
            relevant_context=[*context, *hints],
            delegation_depth=depth,
        )

    def _validate(self, req: HandoffRequest, ctx: RunContext) -> str | None:
        """Return a rejection reason, or None if the handoff is allowed."""
        if req.target_agent not in self.agents:
            return f"unknown target agent '{req.target_agent}'"
        if req.target_agent == req.source_agent:
            return "self-delegation is not allowed"
        source = self.agents.get(req.source_agent)
        if source is None:
            return f"unknown source agent '{req.source_agent}'"
        if not self.policy.allow_agent_to_agent:
            return "agent-to-agent collaboration is disabled by policy"
        if not source.permissions.allow_delegation:
            return f"agent '{req.source_agent}' is not allowed to delegate"
        if req.target_agent not in source.permissions.allowed_agents:
            return f"agent '{req.source_agent}' may not delegate to '{req.target_agent}'"
        for ancestor in ctx.ancestors(req.parent_task_id):
            if ancestor.agent == req.target_agent:
                return (
                    f"circular delegation: '{req.target_agent}' already owns an "
                    "ancestor task in this run"
                )
        if req.delegation_depth > self.policy.max_delegation_depth:
            return (
                f"delegation depth {req.delegation_depth} exceeds the maximum "
                f"{self.policy.max_delegation_depth}"
            )
        if not ctx.reserve_handoff():  # reserve last: rejected handoffs don't consume budget
            return f"max handoffs per run ({self.policy.max_handoffs_per_run}) reached"
        return None

    def _prepare(
        self,
        proposal: DelegationProposal | dict[str, Any],
        *,
        run_id: str,
        parent_task_id: str | None,
        source_agent: str,
    ) -> tuple[RunContext, HandoffRequest | None, HandoffResult | None]:
        ctx = self.context_for(run_id)
        target_hint = proposal.target if isinstance(proposal, DelegationProposal) else None
        ctx.record_event(
            EventType.DELEGATION_REQUESTED,
            source_agent=source_agent,
            target_agent=target_hint,
            metadata={"parent_task_id": parent_task_id},
        )
        try:
            prop = (
                proposal
                if isinstance(proposal, DelegationProposal)
                else DelegationProposal.model_validate(proposal)
            )
        except ValidationError as exc:
            ctx.record_event(
                EventType.DELEGATION_REJECTED,
                source_agent=source_agent,
                target_agent=target_hint,
                metadata={"error": f"malformed delegation proposal: {exc}"},
            )
            return ctx, None, HandoffResult(
                task_id="",
                request_id="",
                run_id=run_id,
                source_agent=source_agent,
                target_agent=target_hint or "",
                status=DelegationStatus.REJECTED,
                error=f"malformed delegation proposal: {exc}",
                started_at=utcnow(),
                finished_at=utcnow(),
            )
        try:
            req = self._build_request(
                prop, run_id=run_id, parent_task_id=parent_task_id,
                source_agent=source_agent, ctx=ctx,
            )
        except ValidationError as exc:  # e.g. self-delegation caught by the model validator
            ctx.record_event(
                EventType.DELEGATION_REJECTED,
                source_agent=source_agent,
                target_agent=prop.target,
                metadata={"error": str(exc)},
            )
            return ctx, None, HandoffResult(
                task_id="",
                request_id="",
                run_id=run_id,
                source_agent=source_agent,
                target_agent=prop.target,
                status=DelegationStatus.REJECTED,
                error=str(exc),
                started_at=utcnow(),
                finished_at=utcnow(),
            )
        reason = self._validate(req, ctx)
        if reason is not None:
            ctx.record_event(
                EventType.DELEGATION_REJECTED,
                task_id=req.task_id,
                request_id=req.request_id,
                source_agent=req.source_agent,
                target_agent=req.target_agent,
                metadata={"error": reason},
            )
            return ctx, req, HandoffResult(
                task_id=req.task_id,
                request_id=req.request_id,
                run_id=run_id,
                source_agent=req.source_agent,
                target_agent=req.target_agent,
                status=DelegationStatus.REJECTED,
                error=reason,
                delegation_depth=req.delegation_depth,
                started_at=utcnow(),
                finished_at=utcnow(),
            )
        ctx.record_event(
            EventType.DELEGATION_APPROVED,
            task_id=req.task_id,
            request_id=req.request_id,
            source_agent=req.source_agent,
            target_agent=req.target_agent,
            metadata={"depth": req.delegation_depth},
        )
        return ctx, req, None

    def _start_task(self, ctx: RunContext, req: HandoffRequest) -> None:
        ctx.create_task(
            task_id=req.task_id,
            parent_task_id=req.parent_task_id,
            agent=req.target_agent,
            description=req.task_description,
            depth=req.delegation_depth,
        )
        ctx.update_task(req.task_id, status=TaskStatus.RUNNING)
        ctx.record_event(
            EventType.TASK_STARTED,
            task_id=req.task_id,
            request_id=req.request_id,
            source_agent=req.source_agent,
            target_agent=req.target_agent,
        )

    def _finish(
        self,
        ctx: RunContext,
        req: HandoffRequest,
        status: TaskStatus,
        *,
        result: str = "",
        error: str | None = None,
        before: int,
        started: str,
        record_result: bool = True,
    ) -> HandoffResult:
        finished = utcnow()
        node = ctx.task(req.task_id)
        # exact per-task count: reservations were counted on the node atomically,
        # so this stays correct even when sibling tasks run in parallel
        model_calls = node.model_calls if node is not None else ctx.model_calls - before
        ctx.update_task(
            req.task_id,
            status=status,
            result=result,
            error=error,
            finished_at=finished,
            model_calls=model_calls,
        )
        if status == TaskStatus.COMPLETED:
            ctx.record_event(
                EventType.TASK_COMPLETED,
                task_id=req.task_id,
                request_id=req.request_id,
                source_agent=req.source_agent,
                target_agent=req.target_agent,
            )
        else:
            ctx.record_event(
                EventType.TASK_FAILED,
                task_id=req.task_id,
                request_id=req.request_id,
                source_agent=req.source_agent,
                target_agent=req.target_agent,
                metadata={"error": error, "status": status.value},
            )
        res = HandoffResult(
            task_id=req.task_id,
            request_id=req.request_id,
            run_id=ctx.run_id,
            source_agent=req.source_agent,
            target_agent=req.target_agent,
            status=DelegationStatus(status.value),
            result=result,
            error=error,
            delegation_depth=req.delegation_depth,
            model_calls=model_calls,
            started_at=started,
            finished_at=finished,
        )
        ctx.set_result(req.request_id, res)
        if record_result:
            ctx.record_event(
                EventType.RESULT_RETURNED,
                task_id=req.task_id,
                request_id=req.request_id,
                source_agent=req.source_agent,
                target_agent=req.target_agent,
                metadata={"status": res.status.value},
            )
        return res

    # ---- sync delegation ----
    def delegate(
        self,
        proposal: DelegationProposal | dict[str, Any],
        *,
        run_id: str,
        parent_task_id: str | None = None,
        source_agent: str,
        timeout: float | None = None,
    ) -> HandoffResult:
        ctx, req, early = self._prepare(
            proposal, run_id=run_id, parent_task_id=parent_task_id, source_agent=source_agent
        )
        if early is not None or req is None:
            return early  # type: ignore[return-value]
        self._start_task(ctx, req)
        target = self.agents[req.target_agent]
        before = ctx.model_calls
        started = utcnow()
        try:
            result = target.run(
                req.task_description,
                context=req.relevant_context,
                run_id=ctx.run_id,
                task_id=req.task_id,
                run_context=ctx,
            )
        except GatewayError as exc:
            return self._finish(
                ctx, req, TaskStatus.FAILED, error=str(exc), before=before, started=started
            )
        except Exception as exc:  # never silently ignore a failed subtask
            return self._finish(
                ctx, req, TaskStatus.FAILED, error=f"{type(exc).__name__}: {exc}",
                before=before, started=started,
            )
        return self._finish(
            ctx, req, TaskStatus.COMPLETED, result=result.answer, before=before, started=started
        )

    def delegate_many(
        self,
        proposals: list[DelegationProposal | dict[str, Any]],
        *,
        run_id: str,
        parent_task_id: str | None = None,
        source_agent: str,
        timeout: float | None = None,
    ) -> list[HandoffResult]:
        """Sync batch: sequential execution, input ordering preserved.

        Identical proposals (same target+task) are executed only once.
        """
        normalized = [self._normalize(p) for p in proposals]
        unique: dict[tuple[str, str], Any] = {}
        order: list[tuple[str, str]] = []
        for prop in normalized:
            key = (prop.target, prop.task)
            if key not in unique:
                unique[key] = prop
                order.append(key)
        results = {
            key: self.delegate(unique[key], run_id=run_id, parent_task_id=parent_task_id,
                               source_agent=source_agent, timeout=timeout)
            for key in order
        }
        return [results[(p.target, p.task)] for p in normalized]

    # ---- async delegation (native; bounded concurrency) ----
    async def adelegate(
        self,
        proposal: DelegationProposal | dict[str, Any],
        *,
        run_id: str,
        parent_task_id: str | None = None,
        source_agent: str,
        timeout: float | None = None,
    ) -> HandoffResult:
        ctx, req, early = self._prepare(
            proposal, run_id=run_id, parent_task_id=parent_task_id, source_agent=source_agent
        )
        if early is not None or req is None:
            return early  # type: ignore[return-value]
        sem = ctx.semaphore()
        async with sem:  # bounded by policy.max_parallel_agents
            self._start_task(ctx, req)
            target = self.agents[req.target_agent]
            before = ctx.model_calls
            started = utcnow()
            effective = (
                timeout if timeout is not None else self.policy.default_delegation_timeout_seconds
            )
            coro = arun_agent(
                target,
                req.task_description,
                context=req.relevant_context,
                run_id=ctx.run_id,
                task_id=req.task_id,
                run_context=ctx,
            )
            try:
                result = await asyncio.wait_for(coro, timeout=effective)
            except TimeoutError:  # asyncio.TimeoutError
                return self._finish(
                    ctx, req, TaskStatus.CANCELLED,
                    error=f"delegation timed out after {effective}s",
                    before=before, started=started,
                )
            except asyncio.CancelledError:
                self._finish(
                    ctx, req, TaskStatus.CANCELLED, error="delegation cancelled",
                    before=before, started=started, record_result=False,
                )
                raise
            except GatewayError as exc:
                return self._finish(
                ctx, req, TaskStatus.FAILED, error=str(exc), before=before, started=started
            )
            except Exception as exc:  # never silently ignore a failed subtask
                return self._finish(
                    ctx, req, TaskStatus.FAILED, error=f"{type(exc).__name__}: {exc}",
                    before=before, started=started,
                )
            return self._finish(
                ctx, req, TaskStatus.COMPLETED, result=result.answer, before=before, started=started
            )

    async def adelegate_many(
        self,
        proposals: list[DelegationProposal | dict[str, Any]],
        *,
        run_id: str,
        parent_task_id: str | None = None,
        source_agent: str,
        timeout: float | None = None,
    ) -> list[HandoffResult]:
        """Parallel batch: bounded by the run semaphore, results in input order.

        Identical proposals (same target+task) are executed only once and share
        the result — no duplicate executions.
        """
        normalized = [self._normalize(p) for p in proposals]
        unique: dict[tuple[str, str], Any] = {}
        order: list[tuple[str, str]] = []
        for prop in normalized:
            key = (prop.target, prop.task)
            if key not in unique:
                unique[key] = prop
                order.append(key)
        # asyncio.gather preserves input order; each adelegate acquires the semaphore
        results = await asyncio.gather(
            *(
                self.adelegate(
                    unique[key], run_id=run_id, parent_task_id=parent_task_id,
                    source_agent=source_agent, timeout=timeout,
                )
                for key in order
            )
        )
        by_key = dict(zip(order, results, strict=True))
        return [by_key[(p.target, p.task)] for p in normalized]

    @staticmethod
    def _normalize(proposal: DelegationProposal | dict[str, Any]) -> DelegationProposal:
        if isinstance(proposal, DelegationProposal):
            return proposal
        return DelegationProposal.model_validate(proposal)
